import {test,expect} from '@playwright/test';
import {authorization,profile,catalog} from './remote-fixtures';
for(const width of [320,390,1000])test(`talent branches and live boundary at ${width}px`,async({page})=>{
 await page.route('https://extension-files.twitch.tv/**',r=>r.fulfill({body:''}));
 await page.setViewportSize({width,height:844});
 await page.goto('/dev-demo/panel.html');
 await page.getByRole('button',{name:'Talente',exact:false}).click();
 const tree=page.getByRole('region',{name:'Talentbaum'});
 await expect(tree.getByRole('status',{name:'Verbleibende Talentpunkte'})).toContainText('0');
 await expect(tree).toContainText('Kräftiger Schlag');
 await tree.getByRole('button',{name:'Angeln',exact:false}).click();
 await expect(tree).toContainText('Ruhige Hand');
 await expect(tree.getByRole('status',{name:'Verbleibende Talentpunkte'})).toBeVisible();
 await expect(tree).not.toContainText('Kräftiger Schlag');
 await tree.getByRole('button',{name:'Tauchen',exact:false}).click();
 await expect(tree).toContainText('Unterwasserjäger');
 await expect(tree).toContainText('Unterwasser-Ausweichen');
 await expect(tree).toContainText('Gilt nicht gegen Bosse');
 for(const b of await tree.getByRole('button',{name:/Keine Talentpunkte verfügbar/}).all())await expect(b).toBeDisabled();
 await page.screenshot({path:`test-results/talents-${width}.png`,fullPage:true});
 await page.route('https://extension-files.twitch.tv/**',r=>r.fulfill({contentType:'text/javascript',body:`window.Twitch={ext:{onAuthorized:cb=>cb(${JSON.stringify(authorization)}),actions:{requestIdShare:()=>{}}}};`}));
 await page.route(/^https:\/\/(?:rc1---)?funjii-otter-rpg-backend-test-cwzl75ajla-ey\.a\.run\.app\//,r=>r.fulfill({json:r.request().url().endsWith('/me')?profile():{available:true,sessionId:'11111111-1111-4111-8111-111111111111',catalogJson:JSON.stringify(catalog())}}));
 await page.goto('/panel.html');
 await page.getByRole('button',{name:'Talente',exact:false}).click();
 await expect(tree).toContainText('Backend-Anbindung ausstehend');
 await expect(tree.getByRole('status',{name:'Verbleibende Talentpunkte'})).toContainText('–');
 await expect(tree.getByRole('button',{name:'Live noch nicht verfügbar'})).toHaveCount(7);
 for(const button of await tree.getByRole('button',{name:'Live noch nicht verfügbar'}).all())await expect(button).toBeDisabled();
});
